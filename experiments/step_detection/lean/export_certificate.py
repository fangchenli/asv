"""Export one archived certificate's exact scalar arithmetic to Lean."""

# Lean's real and rational type notation is intentional in generated source.
# ruff: noqa: RUF001

import argparse
import hashlib
import json
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ARCHIVE = ROOT.parent / 'data' / 'sturm_v1_diagnosis.json'
OUTPUT = ROOT / 'StepDetection' / 'SavedCertificate.lean'
CASE_ID = 'negative-directional-ar1-study-n100-d0.08-s0.02-early-seed1601'


def render(archive):
    data = json.loads(archive)
    row = next(row for row in data['rows'] if row['id'] == CASE_ID)
    certificate = row['interval_certificate']
    attempt = next(a for a in certificate['attempts'] if a['tilt'] == certificate['selected_tilt'])
    constants = {
        'rhoLeft': certificate['left'],
        'rhoRight': certificate['right'],
        'detLower': attempt['base']['determinant_enclosure'][0],
        'correctionLower': attempt['density_correction'],
        'squaredUpper': certificate['p_upper_squared'],
        'displayUpper': certificate['p_upper'],
        'delta': certificate['delta'],
    }
    definitions = '\n'.join(
        f'def {name} : ℚ := {q.numerator} / {q.denominator}'
        for name, value in constants.items()
        for q in [Fraction(value)]
    )
    return f'''-- Generated by export_certificate.py; do not edit by hand.
-- Archive: data/sturm_v1_diagnosis.json
-- SHA256: {hashlib.sha256(archive).hexdigest()}
-- Case: {CASE_ID}
-- Interval certificate, tilt {certificate['selected_tilt']}, count {certificate['selected_count']}.
import StepDetection.Certificate

namespace StepDetection.Saved

{definitions}

-- These are proofs about the exact archived fractions, not Python assertions.
theorem scalar_checks :
    rhoLeft < rhoRight ∧
    0 < detLower ∧ 1 ≤ correctionLower ∧
    squaredUpper = 1 / (detLower * correctionLower ^ 2) ∧
    0 ≤ displayUpper ∧ squaredUpper ≤ displayUpper ^ 2 ∧
    displayUpper < delta ∧ delta = 1 / 100 := by
  norm_num [rhoLeft, rhoRight, detLower, correctionLower,
    squaredUpper, displayUpper, delta]

-- The caller still has to prove the probability inequality.
theorem saved_cutoff {{p : ℝ}} (hprob : p ^ 2 ≤ (squaredUpper : ℝ)) :
    p < (1 : ℝ) / 100 := by
  rcases scalar_checks with ⟨_, _, _, _, hnonneg, hsquare, hcutoff, hdelta⟩
  apply cutoff_of_squared_bound hprob (upper := (displayUpper : ℝ))
  · exact_mod_cast hsquare
  · exact_mod_cast hnonneg
  · have hcutoff' : (displayUpper : ℝ) < (delta : ℝ) := by exact_mod_cast hcutoff
    norm_num [delta] at hcutoff'
    exact hcutoff'

-- Also expose the determinant and density-correction assumptions explicitly.
theorem saved_model_cutoff {{p det correction : ℝ}}
    (hdet : (detLower : ℝ) ≤ det)
    (hcorr : (correctionLower : ℝ) ≤ correction)
    (hprob : p ^ 2 ≤ 1 / (det * correction ^ 2)) : p < (1 : ℝ) / 100 := by
  rcases scalar_checks with ⟨_, hd, hc, heq, _⟩
  apply saved_cutoff
  have hd' : (0 : ℝ) < (detLower : ℝ) := by exact_mod_cast hd
  have hc' : (0 : ℝ) < (correctionLower : ℝ) := by
    have : (0 : ℚ) < correctionLower := lt_of_lt_of_le (by norm_num) hc
    exact_mod_cast this
  have heq' : (squaredUpper : ℝ) =
      1 / ((detLower : ℝ) * (correctionLower : ℝ) ^ 2) := by exact_mod_cast heq
  rw [heq']
  exact hprob.trans (reciprocal_square_bound hd' hc' hdet hcorr)

end StepDetection.Saved
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Reject stale generated source')
    args = parser.parse_args()
    expected = render(ARCHIVE.read_bytes())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            parser.exit(1, 'SavedCertificate.lean is stale; run export_certificate.py\n')
        print('Saved certificate source matches the archive.')
    else:
        OUTPUT.write_text(expected)
        print(f'Wrote {OUTPUT.name}')


if __name__ == '__main__':
    main()
