"""Connect saved scalar nodes to tridiagonal pivots and both matrix solves."""

# Lean type notation is intentional in generated source.
# ruff: noqa: RUF001

import argparse
from pathlib import Path

from export_trace import collect

ROOT = Path(__file__).resolve().parent


def value(node):
    return f'v{node.index} rho'


def vector(items):
    return '![' + ', '.join(items) + ']'


def render():
    capture = {}
    nodes, metadata = collect(capture=capture)
    n = metadata['n']
    if n != 100 or metadata['split'] != 1:
        raise ValueError('This bridge is for the saved 100-observation, split-1 case')
    pivots = capture['pivots']
    multipliers = [None, *capture['multipliers']]
    solves = sorted(capture['solves'], key=lambda s: s['start'])
    endpoint, interior, off = (value(capture[k]) for k in ('endpoint', 'interior', 'off'))
    header = '-- Generated by export_matrix.py; do not edit by hand.\n'
    preamble = 'set_option maxRecDepth 2048\n\nnamespace StepDetection.DeterminantTrace\n\n'
    files = {}
    definitions = {
        'pivots': vector([value(p) for p in pivots]),
        'multipliers': vector(['0', *[value(m) for m in multipliers[1:]]]),
    }
    for j, solve in enumerate(solves):
        definitions[f'forward{j}'] = vector([value(v) for v in solve['forward']])
        definitions[f'solution{j}'] = vector([value(v) for v in solve['result']])
    body = '\n'.join(
        f'noncomputable def {name} (rho : ℝ) : Fin 100 → ℝ := {expression}'
        for name, expression in definitions.items()
    )
    body += f'''
noncomputable def diagonal (rho : ℝ) (i : Fin 100) : ℝ :=
  if i.val = 0 ∨ i.val = 99 then {endpoint} else {interior}
noncomputable def offDiagonal (rho : ℝ) (_i : Fin 100) : ℝ := {off}
noncomputable def precisionShift (rho : ℝ) := Tridiagonal.matrix (diagonal rho) (offDiagonal rho)
def plateauColumns : Matrix (Fin 100) (Fin 2) ℝ := fun i j =>
  if j.val = 0 then (if i.val = 0 then 1 else 0) else (if i.val = 0 then 0 else 1)
noncomputable def forwardMatrix (rho : ℝ) : Matrix (Fin 100) (Fin 2) ℝ := fun i =>
  ![forward0 rho i, forward1 rho i]
noncomputable def solutionMatrix (rho : ℝ) : Matrix (Fin 100) (Fin 2) ℝ := fun i =>
  ![solution0 rho i, solution1 rho i]
'''
    files['Data.lean'] = (
        header + 'import StepDetection.DeterminantTrace.Result\n'
        'import StepDetection.Tridiagonal\nimport Mathlib.Tactic.FinCases\n'
        + preamble
        + body
        + '\nend StepDetection.DeterminantTrace\n'
    )
    previous = 'Data'
    for start in range(0, n, 10):
        body = ''
        for i in range(start, min(n, start + 10)):
            p = pivots[i]
            body += f'''theorem pivot_positive_{i} {{rho : ℝ}} (hrho : inputBounds.Contains rho) :
    0 < {value(p)} :=
  lt_of_lt_of_le (by norm_num [b{p.index}]) (h{p.index} hrho).1

'''
            if i:
                prev, m = value(pivots[i - 1]), value(multipliers[i])
                diag = endpoint if i == n - 1 else interior
                body += f'''theorem off_equation_{i} {{rho : ℝ}} (hrho : inputBounds.Contains rho) :
    {off} = ({m}) * ({prev}) := by
  change {off} = (({off}) * (1 / ({prev}))) * ({prev})
  field_simp [ne_of_gt (pivot_positive_{i - 1} hrho)]

theorem pivot_equation_{i} {{rho : ℝ}} (hrho : inputBounds.Contains rho) :
    {diag} = {value(p)} + ({m}) * ({prev}) * ({m}) := by
  change {diag} = ({diag} - ({m}) * ({off})) + ({m}) * ({prev}) * ({m})
  rw [off_equation_{i} hrho]
  ring

'''
        name = f'Pivots{start // 10:02}'
        files[f'{name}.lean'] = (
            header
            + f'import StepDetection.SavedMatrix.{previous}\n'
            + preamble
            + body
            + 'end StepDetection.DeterminantTrace\n'
        )
        previous = name

    body = '''theorem pivots_positive {rho : ℝ} (hrho : inputBounds.Contains rho) :
    ∀ i, 0 < pivots rho i := by
  intro i
  fin_cases i
'''
    body += ''.join(f'  · exact pivot_positive_{i} hrho\n' for i in range(n))
    body += '''
theorem off_equations {rho : ℝ} (hrho : inputBounds.Contains rho) :
    ∀ i, i.val ≠ 0 → offDiagonal rho i =
      multipliers rho i * pivots rho (Tridiagonal.previous i) := by
  intro i hi
  fin_cases i
  · exact (hi rfl).elim
'''
    body += ''.join(f'  · exact off_equation_{i} hrho\n' for i in range(1, n))
    body += '''
theorem pivot_equations {rho : ℝ} (hrho : inputBounds.Contains rho) :
    ∀ i, diagonal rho i = pivots rho i + if i.val = 0 then 0 else
      multipliers rho i * pivots rho (Tridiagonal.previous i) * multipliers rho i := by
  intro i
  fin_cases i
  · exact (add_zero _).symm
'''
    body += ''.join(f'  · exact pivot_equation_{i} hrho\n' for i in range(1, n))
    body += '''
theorem saved_factorization {rho : ℝ} (hrho : inputBounds.Contains rho) :
    precisionShift rho = Tridiagonal.lower (multipliers rho) *
      Matrix.diagonal (pivots rho) * (Tridiagonal.lower (multipliers rho))ᵀ :=
  Tridiagonal.factorization _ _ _ _ (pivot_equations hrho) (off_equations hrho)

theorem saved_pivot_product {rho : ℝ} (hrho : inputBounds.Contains rho) :
    (precisionShift rho).det = ∏ i, pivots rho i :=
  Tridiagonal.determinant _ _ _ _ (pivot_equations hrho) (off_equations hrho)
'''
    files['Factorization.lean'] = (
        header
        + f'import StepDetection.SavedMatrix.{previous}\n'
        + preamble
        + 'open Matrix\n\n'
        + body
        + '\nend StepDetection.DeterminantTrace\n'
    )
    body = '''theorem forward_equations (rho : ℝ) :
    ∀ i j, forwardMatrix rho i j = plateauColumns i j - if i.val = 0 then 0 else
      multipliers rho i * forwardMatrix rho (Tridiagonal.previous i) j := by
  intro i j
  fin_cases i <;> fin_cases j
'''
    for i in range(n):
        for j, solve in enumerate(solves):
            rhs = 1 if solve['start'] <= i < solve['stop'] else 0
            f = value(solve['forward'][i])
            if i == 0:
                body += f'  · change {f} = {rhs} - 0\n    norm_num [v{rhs}]\n'
            else:
                m, prev = value(multipliers[i]), value(solve['forward'][i - 1])
                body += f'''  · change v{rhs} rho - ({m}) * ({prev}) = {rhs} - ({m}) * ({prev})
    simp only [v{rhs}, div_one]
'''
    body += '''
set_option maxHeartbeats 800000 in
theorem backward_equations (rho : ℝ) :
    ∀ i j, solutionMatrix rho i j = forwardMatrix rho i j / pivots rho i -
      if h : i.val + 1 < 100 then multipliers rho (Tridiagonal.next i h) *
        solutionMatrix rho (Tridiagonal.next i h) j else 0 := by
  intro i j
  fin_cases i <;> fin_cases j
'''
    for i in range(n):
        for solve in solves:
            f, p = value(solve['forward'][i]), value(pivots[i])
            term = (
                f'({value(multipliers[i + 1])}) * ({value(solve["result"][i + 1])})'
                if i < n - 1
                else '0'
            )
            left = f'({f}) * (1 / ({p}))' + (f' - {term}' if i < n - 1 else '')
            simp = 'div_eq_mul_inv, one_mul' + (', sub_zero' if i == n - 1 else '')
            body += f'''  · change {left} = ({f}) / ({p}) - {term}
    simp only [{simp}]
'''
    body += '''
theorem saved_solve {rho : ℝ} (hrho : inputBounds.Contains rho) :
    precisionShift rho * solutionMatrix rho = plateauColumns :=
  Tridiagonal.solve _ _ _ _ _ _ _ (pivot_equations hrho) (off_equations hrho)
    (fun i => ne_of_gt (pivots_positive hrho i)) (forward_equations rho) (backward_equations rho)

theorem saved_det_positive {rho : ℝ} (hrho : inputBounds.Contains rho) :
    0 < (precisionShift rho).det := by
  rw [saved_pivot_product hrho]
  exact Finset.prod_pos (fun i _ => pivots_positive hrho i)

theorem saved_inverse_solve {rho : ℝ} (hrho : inputBounds.Contains rho) :
    (precisionShift rho)⁻¹ * plateauColumns = solutionMatrix rho := by
  let _ := Matrix.invertibleOfIsUnitDet _
    (isUnit_iff_ne_zero.mpr (ne_of_gt (saved_det_positive hrho)))
  exact Tridiagonal.inverse_solve _ _ _ (saved_solve hrho)
'''
    files['Solves.lean'] = (
        header
        + 'import StepDetection.SavedMatrix.Factorization\n'
        + preamble
        + body
        + '\nend StepDetection.DeterminantTrace\n'
    )
    product_nodes = []
    current = capture['determinant'].index
    for p in reversed(pivots[1:]):
        node = nodes[current]
        if node['op'] != 'mul' or node['args'][1] != p.index:
            raise ValueError('Unexpected determinant product structure')
        product_nodes.append(f'v{current}')
        current = node['args'][0]
    if current != pivots[0].index:
        raise ValueError('Unexpected determinant product initial value')
    files['Product.lean'] = (
        header
        + 'import StepDetection.SavedMatrix.Solves\n'
        + preamble
        + f'''
theorem recorded_product (rho : ℝ) :
    {value(capture['determinant'])} = ∏ i, pivots rho i := by
  simp only [pivots, {', '.join(product_nodes)}, Fin.prod_univ_succ,
    Fin.prod_univ_zero, Matrix.cons_val_zero, Matrix.cons_val_succ, mul_one, mul_assoc]

theorem saved_determinant {{rho : ℝ}} (hrho : inputBounds.Contains rho) :
    (precisionShift rho).det = {value(capture['determinant'])} := by
  rw [saved_pivot_product hrho, recorded_product]

end StepDetection.DeterminantTrace
'''
    )
    gram = capture['gram']
    gram_values = '; '.join(', '.join(value(v) for v in row) for row in gram)
    body = f'noncomputable def recordedGram (rho : ℝ) : Matrix (Fin 2) (Fin 2) ℝ := !![{gram_values}]\n\n'
    body += '''theorem plateau_gram :
    plateauColumnsᵀ * plateauColumns = (!![1, 0; 0, 99] : Matrix (Fin 2) (Fin 2) ℝ) := by
  ext i j
  fin_cases i <;> fin_cases j <;>
    norm_num [Matrix.mul_apply, plateauColumns, Fin.sum_univ_succ]

theorem plateau_gram_det : (plateauColumnsᵀ * plateauColumns).det = 99 := by
  rw [plateau_gram, Matrix.det_fin_two]
  norm_num

theorem recorded_gram (rho : ℝ) :
    recordedGram rho = (v2 rho)⁻¹ •
      (plateauColumnsᵀ * plateauColumns - v7 rho • (plateauColumnsᵀ * solutionMatrix rho)) := by
  rw [plateau_gram]
  ext i j
  fin_cases i <;> fin_cases j
'''
    for i in range(2):
        for j in range(2):
            node_index = gram[i][j].index
            unfolded = []
            # Expand the scalar formula and its sum, but leave solve values opaque.
            queue = [node_index]
            boundaries = {capture['shift'].index, capture['ai'].index}
            boundaries.update(v.index for s in solves for v in s['result'])
            while queue:
                index = queue.pop()
                if index in boundaries or index in unfolded:
                    continue
                unfolded.append(index)
                queue.extend(nodes[index]['args'])
            definitions = ', '.join(f'v{index}' for index in unfolded)
            body += f'''  · norm_num [recordedGram, Matrix.mul_apply, plateauColumns,
      solutionMatrix, solution0, solution1, Fin.sum_univ_succ,
      {definitions}]
    ring
'''
    body += '''
theorem recorded_final_formula (rho : ℝ) :
    determinantExpression rho = v508 rho * (recordedGram rho).det / (v6 rho * 99) := by
  simp only [determinantExpression, v1722, v1721, v1720, v1719, v1718, v1717, v1716,
    v1712, recordedGram, Matrix.det_fin_two]
  norm_num
  ring

end StepDetection.DeterminantTrace
'''
    files['Gram.lean'] = (
        header + 'import StepDetection.SavedMatrix.Product\n' + preamble + 'open Matrix\n\n' + body
    )
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = render()
    directory = ROOT / 'StepDetection' / 'SavedMatrix'
    if args.check:
        existing = {p.name for p in directory.iterdir()} if directory.exists() else set()
        if existing != set(files) or any(
            (directory / name).read_text() != text for name, text in files.items()
        ):
            parser.exit(1, 'Saved matrix bridge is stale; run export_matrix.py\n')
    else:
        directory.mkdir(exist_ok=True)
        if any(p.name not in files for p in directory.iterdir()):
            parser.exit(1, 'Unexpected files in saved matrix directory\n')
        for name, text in files.items():
            path = directory / name
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
    print('Saved matrix bridge matches the recorded pivots and solves.')


if __name__ == '__main__':
    main()
